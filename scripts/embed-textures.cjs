// Embed local licensed textures so WebGL works over file:// without CORS flags.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const maps = {};
for (const name of ['asphalt', 'concrete', 'tiles']) {
  maps[name] = {};
  for (const kind of ['color', 'normal']) {
    const bytes = fs.readFileSync(path.join(root, 'assets', 'textures', `${name}-${kind}.jpg`));
    maps[name][kind] = 'data:image/jpeg;base64,' + bytes.toString('base64');
  }
}
fs.writeFileSync(path.join(root, 'assets', 'textures.js'), '// Generated by scripts/embed-textures.cjs; see textures/LICENSE.md.\nwindow.NightTextures = ' + JSON.stringify(maps) + ';\n');
